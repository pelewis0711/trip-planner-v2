// Phase 26: picked activities are stored by permanent id, not list position.
//
// Before this, Stop.act was a boolean[] "parallel to Trip.a" -- box #3
// checked meant "whatever activity sits third in the list." Adding,
// removing or reordering a single activity would have silently moved every
// saved pick onto a different activity. Now Stop.act is the list of picked
// activity ids ("rome.borghese-gallery"), which survive any edit to the
// catalog.
//
// Old position-based picks still exist in three places this app reads from:
// localStorage (migrated by the plan store's persist migration), synced
// Supabase rows (rowToPlan), and exported plan files (planIO). All three go
// through migrateAct() below. The readers in this file also accept the old
// shape directly, so a stray old-format stop can never mis-price or crash.
import { TRIPS, type Trip } from "@/data/trips";
import LEGACY_ACTIVITY_MAP from "@/data/legacyActivityMap.json";

// How old positions (each trip's activity order as of Oct 19, 2026, before
// ids existed) map onto today's catalog. Generated by extract-trips.mjs from
// the frozen snapshot in scripts/data/legacyActivityOrder.json. Only trips
// whose order has changed since then are listed: each entry gives, per old
// position, the activity's current index in trip.a, or its id if it has left
// the catalog. A trip with no entry kept its original order.
export type LegacyActivityMap = Record<string, (number | string)[]>;
const LEGACY_MAP: LegacyActivityMap = LEGACY_ACTIVITY_MAP;
const TRIP_BY_ID = new Map(TRIPS.map((t) => [t.id, t]));

/** The id of the activity that sat at `index` in a trip's list before ids
 * existed, or undefined if there was none. `map` is only overridden by tests. */
export function legacyActivityId(
  tripId: string,
  index: number,
  map: LegacyActivityMap = LEGACY_MAP,
  trips: Map<string, Trip> = TRIP_BY_ID
): string | undefined {
  const t = trips.get(tripId);
  const entry = map[tripId];
  if (!entry) return t?.a[index]?.[2];
  const v = entry[index];
  if (typeof v === "number") return t?.a[v]?.[2];
  return typeof v === "string" ? v : undefined;
}

const MAX_PICKS = 200;
const MAX_ID_LENGTH = 120;
// "<tripId>.<slug>" -- trip ids are letters/digits (one has a capital), the
// slug is lowercase words joined by single hyphens.
const ID_SHAPE = /^[A-Za-z0-9]+\.[a-z0-9]+(-[a-z0-9]+)*$/;

export function isActivityId(v: unknown): v is string {
  return typeof v === "string" && v.length <= MAX_ID_LENGTH && ID_SHAPE.test(v);
}

/** Converts whatever is stored on a stop's `act` into a clean list of picked
 * activity ids. Old format (booleans by position) is mapped through the
 * frozen legacy order; new format (ids) is kept, de-duplicated and shape-
 * checked. Anything else (missing, garbage) becomes no picks. Never throws. */
export function migrateAct(tripId: string, act: unknown, map?: LegacyActivityMap): string[] {
  if (!Array.isArray(act)) return [];
  const out: string[] = [];
  const seen = new Set<string>();
  const add = (id: string) => {
    if (!seen.has(id) && out.length < MAX_PICKS) {
      seen.add(id);
      out.push(id);
    }
  };
  act.forEach((v, i) => {
    if (v === true) {
      const id = legacyActivityId(tripId, i, map);
      if (id) add(id);
    } else if (isActivityId(v)) {
      add(v);
    }
  });
  return out;
}

export interface PickedActivity {
  id: string;
  name: string;
  price: number;
  /** false when the id is no longer in this trip's catalog. The pick is
   * kept (warnings never delete user choices) but counted at $0. */
  listed: boolean;
}

/** A stop's picked activities: listed ones in catalog order, then any that
 * are no longer listed. */
export function pickedActivities(t: Trip, act: readonly unknown[] | undefined): PickedActivity[] {
  const ids = migrateAct(t.id, act);
  if (!ids.length) return [];
  const picked = new Set(ids);
  const out: PickedActivity[] = [];
  for (const [name, price, id] of t.a) {
    if (picked.has(id)) {
      out.push({ id, name, price, listed: true });
      picked.delete(id);
    }
  }
  for (const id of ids) {
    if (picked.has(id)) out.push({ id, name: nameFromId(id), price: 0, listed: false });
  }
  return out;
}

/** Sum of picked, still-listed activity prices (per person). */
export function pickedActivityTotal(t: Trip, act: readonly unknown[] | undefined): number {
  return pickedActivities(t, act).reduce((s, a) => s + a.price, 0);
}

/** Readable fallback name for an activity that has left the catalog:
 * "rome.borghese-gallery" -> "Borghese gallery". */
export function nameFromId(id: string): string {
  const slug = id.slice(id.indexOf(".") + 1).replace(/-/g, " ");
  return slug.charAt(0).toUpperCase() + slug.slice(1);
}

/** Every stop in a placements map with its picks converted to ids. Used by
 * the plan store's persist migration and by rowToPlan for synced rows. */
export function placementsWithActivityIds<P extends { stops: { tripId: string; act: unknown }[] }>(
  placements: Record<string, P> | undefined
): Record<string, P> {
  const out: Record<string, P> = {};
  for (const [slotId, p] of Object.entries(placements ?? {})) {
    out[slotId] = {
      ...p,
      stops: (p.stops ?? []).map((s) => ({ ...s, act: migrateAct(s.tripId, s.act) })),
    };
  }
  return out;
}
