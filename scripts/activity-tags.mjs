// Phase 26 step 2: activity tags -- shared by extract-trips.mjs (compiles
// them into the app's data files) and validate-activity-expansions.mjs
// (checks them).
//
// AUTHORING: src/data/activityTags/<batch>.json, hand-written, one file per
// batch of trips. Shape:
//
//   {
//     "rome": {
//       "colosseum-and-forum-and-palatine": ["landmarks", "half", "day", "must book", "One ticket covers the arena, the Forum and Palatine Hill"],
//       ...
//     }
//   }
//
// Keys are the trip id, then the activity id WITHOUT the "<tripId>." prefix.
// Each value is [category, duration, when, flags, description]:
//   category    one of CATEGORIES below
//   duration    short (under 2h) | half (half day) | full (full day) | overnight
//   when        day | night | any
//   flags       "" or space-separated: must (a must-do; 2-4 per city),
//               book (book ahead: sells out or needs a timed slot)
//   description one line, at most 90 characters, own words
//
// A trip is either fully tagged (every activity) or not tagged at all.
//
// COMPILED (regenerated by extract-trips.mjs, never hand-edited), both
// aligned with each trip's current activity order:
//   src/data/activityMeta.json          { tripId: [[cat, dur, when, flagBits] | null, ...] }
//     -- small, ships with the app (filters and must-do need it everywhere)
//   src/data/activityDescriptions.json  { tripId: [description, ...] }
//     -- larger, loaded on demand by src/lib/activityDescriptions.ts
import { readdirSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";

// Order matters: compiled meta stores the index. Append new values only.
// Keep in sync with src/lib/activityMeta.ts (a test checks this).
export const CATEGORIES = [
  "landmarks", "museums", "sacred", "food", "drink", "nightlife", "nature",
  "water", "adventure", "views", "walks", "daytrips", "classes", "shopping",
];
export const DURATIONS = ["short", "half", "full", "overnight"];
export const WHEN = ["day", "night", "any"];
export const FLAG_BITS = { must: 1, book: 2 };
export const MAX_DESCRIPTION = 90;
export const MUST_MIN = 2;
export const MUST_MAX = 4;

/** Reads every authoring file: { file, tripId, tags: {slug: entry} }[]. */
export function loadTagSources(root) {
  const dir = path.join(root, "src/data/activityTags");
  if (!existsSync(dir)) return [];
  const out = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const data = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
    for (const [tripId, tags] of Object.entries(data)) out.push({ file, tripId, tags });
  }
  return out;
}

/** Checks the authoring files against the trips. Returns { errors, warnings }
 * as lists of strings. `trips` are objects with id, n and a: [name, price, id][]. */
export function validateTags(trips, sources) {
  const errors = [];
  const warnings = [];
  const byId = new Map(trips.map((t) => [t.id, t]));
  const seenTrip = new Map();

  for (const { file, tripId, tags } of sources) {
    const where = `${file} ${tripId}`;
    const t = byId.get(tripId);
    if (!t) {
      errors.push(`${where}: no such trip`);
      continue;
    }
    if (seenTrip.has(tripId)) {
      errors.push(`${where}: also tagged in ${seenTrip.get(tripId)}`);
      continue;
    }
    seenTrip.set(tripId, file);

    const slugs = new Map(t.a.map(([name, , id]) => [id.slice(tripId.length + 1), name]));
    for (const slug of Object.keys(tags)) {
      if (!slugs.has(slug)) errors.push(`${where}: unknown activity "${slug}"`);
    }
    let must = 0;
    const descs = new Set();
    for (const [slug, name] of slugs) {
      const entry = tags[slug];
      if (!entry) {
        errors.push(`${where}: "${name}" (${slug}) is not tagged -- a trip must be tagged completely`);
        continue;
      }
      if (!Array.isArray(entry) || entry.length !== 5) {
        errors.push(`${where} ${slug}: expected [category, duration, when, flags, description]`);
        continue;
      }
      const [cat, dur, when, flags, desc] = entry;
      if (!CATEGORIES.includes(cat)) errors.push(`${where} ${slug}: unknown category "${cat}"`);
      if (!DURATIONS.includes(dur)) errors.push(`${where} ${slug}: unknown duration "${dur}"`);
      if (!WHEN.includes(when)) errors.push(`${where} ${slug}: unknown when "${when}"`);
      const tokens = typeof flags === "string" ? flags.split(" ").filter(Boolean) : null;
      if (!tokens || tokens.some((f) => !(f in FLAG_BITS)) || new Set(tokens).size !== tokens.length) {
        errors.push(`${where} ${slug}: bad flags "${flags}" (use "", "must", "book" or "must book")`);
      } else if (tokens.includes("must")) {
        must++;
      }
      if (typeof desc !== "string" || !desc.trim()) {
        errors.push(`${where} ${slug}: missing description`);
      } else {
        if (desc.length > MAX_DESCRIPTION) errors.push(`${where} ${slug}: description is ${desc.length} chars (max ${MAX_DESCRIPTION})`);
        if (desc !== desc.trim() || /\s{2}/.test(desc)) errors.push(`${where} ${slug}: description has stray spaces`);
        if (desc.trim().toLowerCase() === name.trim().toLowerCase()) warnings.push(`${where} ${slug}: description just repeats the name`);
        if (descs.has(desc)) warnings.push(`${where} ${slug}: same description as another activity`);
        descs.add(desc);
      }
    }
    if (must < MUST_MIN || must > MUST_MAX) {
      errors.push(`${where}: ${must} must-dos, expected ${MUST_MIN}-${MUST_MAX}`);
    }
  }
  return { errors, warnings, taggedTrips: seenTrip.size };
}

/** Builds the two compiled files, aligned with each trip's activity order.
 * Untagged trips are left out (the app treats them as "no tags yet"). */
export function compileTags(trips, sources) {
  const byTrip = new Map(sources.map((s) => [s.tripId, s.tags]));
  const meta = {};
  const descriptions = {};
  for (const t of trips) {
    const tags = byTrip.get(t.id);
    if (!tags) continue;
    meta[t.id] = t.a.map(([, , id]) => {
      const e = tags[id.slice(t.id.length + 1)];
      if (!e) return null;
      const bits = e[3].split(" ").filter(Boolean).reduce((b, f) => b | (FLAG_BITS[f] ?? 0), 0);
      return [CATEGORIES.indexOf(e[0]), DURATIONS.indexOf(e[1]), WHEN.indexOf(e[2]), bits];
    });
    descriptions[t.id] = t.a.map(([, , id]) => tags[id.slice(t.id.length + 1)]?.[4] ?? "");
  }
  return { meta, descriptions };
}

/** JSON with one trip per line: small diffs, still compact. */
export function stringifyByTrip(obj) {
  const lines = Object.entries(obj).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`);
  return lines.length ? `{\n${lines.join(",\n")}\n}\n` : "{}\n";
}
